  @override
  Future<List<ActivityModel>> getRecentActivities({
    int limit = 50,
    ActivityCategory? category,
    ActivityType? type,
  }) async {
    var list = _activities;
    if (type != null) {
      list = list.where((a) => a.type == type).toList();
    } else if (category != null) {
      list = list.where((a) => a.category == category).toList();
    }
    return list.take(limit).toList();
  }

  Future<PaginatedResult<ActivityModel>> getPaginatedActivities({
    int page = 1,
    int limit = 10,
    ActivityCategory? category,
    ActivityType? type,
    String? searchQuery,
  }) async {
    var list = _activities;
    if (type != null) {
      list = list.where((a) => a.type == type).toList();
    } else if (category != null) {
      list = list.where((a) => a.category == category).toList();
    }

    if (searchQuery != null && searchQuery.trim().isNotEmpty) {
      final q = searchQuery.toLowerCase().trim();
      list = list.where((a) {
        return a.title.toLowerCase().contains(q) ||
            a.description.toLowerCase().contains(q) ||
            a.counterparty.toLowerCase().contains(q) ||
            a.reference.toLowerCase().contains(q);
      }).toList();
    }

    return PaginatedResult.paginateList(list, page: page, limit: limit);
  }

  @override
  Future<ActivityModel> recordActivity(ActivityModel activity) async {
    final idx = _activities.indexWhere(
      (a) =>
          a.id == activity.id ||
          (a.reference.isNotEmpty && a.reference == activity.reference),
    );
    if (idx != -1) {
      _activities[idx] = activity;
    } else {
      _activities.insert(0, activity);
    }
    return activity;
  }


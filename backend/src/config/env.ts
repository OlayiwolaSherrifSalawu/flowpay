import dotenv from 'dotenv';
import { z } from 'zod';

dotenv.config();

const envSchema = z.object({
  PORT: z.string().default('4000').transform((val) => parseInt(val, 10)),
  NODE_ENV: z.enum(['development', 'test', 'production']).default('development'),
  DATABASE_URL: z.string().default('postgresql://postgres:flowpay@localhost:5432/flowpay'),
  FLOWPAY_JWT_SECRET: z.string().default('flowpay_development_secret_change_in_production_min32chars'),
  APP_URL: z.string().default('https://app.flowpay.finance'),
  // Stellar network configuration (see .agents/skills/stellar/SKILL.md)
  STELLAR_NETWORK: z.enum(['testnet', 'public']).default('testnet'),
  STELLAR_HORIZON_URL: z.string().optional(),
  STELLAR_FRIENDBOT_URL: z.string().default('https://friendbot.stellar.org'),
  // Public key of the account that issues FlowPay's testnet USD/CAD/MXN/GBP/NGN assets.
  STELLAR_ASSET_ISSUER: z.string().optional(),
  // Per-asset override "CODE:ISSUER" (e.g. mainnet Circle USDC) — takes precedence over STELLAR_ASSET_ISSUER.
  STELLAR_ASSET_USD: z.string().optional(),
  STELLAR_ASSET_CAD: z.string().optional(),
  STELLAR_ASSET_MXN: z.string().optional(),
  STELLAR_ASSET_GBP: z.string().optional(),
  STELLAR_ASSET_NGN: z.string().optional(),
  // Server-side testnet treasury (market maker + test-funds faucet). Generated by `npm run stellar:bootstrap`.
  STELLAR_DISTRIBUTOR_SECRET: z.string().optional(),
  GEMINI_API_KEY: z.string().optional(),
  // Mail Configuration (Gmail SMTP)
  SMTP_HOST: z.string().default('smtp.gmail.com'),
  SMTP_PORT: z.string().default('587').transform((val) => parseInt(val, 10)),
  SMTP_SECURE: z.string().default('false').transform((val) => val === 'true'),
  SMTP_USER: z.string().default(''),
  SMTP_PASS: z.string().default(''),
  MAIL_FROM_NAME: z.string().default('FlowPay'),
  MAIL_FROM_ADDRESS: z.string().default('onboarding@resend.dev'),
  RESEND_API_KEY: z.string().default(''),
  MAILGUN_API_KEY: z.string().optional(),
  MAILGUN_DOMAIN: z.string().optional(),
  MAILGUN_BASE_URL: z.string().default('https://api.mailgun.net/v3'),
  // Paystack Configuration
  PAYSTACK_SECRET_KEY: z.string().optional(),
  PAYSTACK_BASE_URL: z.string().default('https://api.paystack.co').transform((url) => {
    return url.replace(/\/$/, '');
  }),
});

export const env = envSchema.parse(process.env);
